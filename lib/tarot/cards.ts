export type TarotCategory = "major-arcana" | "cups" | "pentacles" | "swords" | "wands";

export interface TarotCard {
  id: string;
  name: string;
  image: string;
  category: TarotCategory;
  keywords: string[];
  basicMeaning: string;
  reversedMeaning: string;
}

function card(
  category: TarotCategory,
  id: string,
  name: string,
  ext: string,
  keywords: string[],
  basicMeaning: string,
  reversedMeaning: string,
): TarotCard {
  return {
    id,
    name,
    image: `/cards/${category}/${id}.${ext}`,
    category,
    keywords,
    basicMeaning,
    reversedMeaning,
  };
}

